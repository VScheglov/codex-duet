const plural = (n: number, one: string, few: string, many: string) => {
  const last = Math.abs(n) % 10
  const lastTwo = Math.abs(n) % 100
  return last === 1 && lastTwo !== 11 ? one : last >= 2 && last <= 4 && (lastTwo < 12 || lastTwo > 14) ? few : many
}

